export function translateRegionalText(
  lang: Language,
  enText: string,
  hiText?: string,
  regionalOverrides?: RegionalPhraseMap
): string {
  if (!enText && !hiText) return '';
  if (lang === 'en') return enText || hiText || '';
  if (lang === 'hi') return hiText || enText || '';
  if (!isRegionalLanguage(lang)) return enText;

  if (regionalOverrides && regionalOverrides[lang]) {
    return regionalOverrides[lang] as string;
  }

  const clean = (enText || '').trim();
  const exact = REGIONAL_UI_DICTIONARY[clean];
  if (exact && exact[lang]) {
    return exact[lang];
  }

  // If we have Hindi text (Devanagari), adapt it into the target regional language & script
  // so that body paragraphs, overviews, roadmaps, quiz questions, and options are 100% localized!
  if (hiText && /[\u0900-\u097F]/.test(hiText)) {
    let adapted = hiText;
    if (lang === 'mr') {
      adapted = adaptHindiToMarathi(hiText);
    } else if (lang === 'gu') {
      adapted = adaptHindiToGujarati(hiText);
    } else if (lang === 'bn') {
      adapted = adaptHindiToBengali(hiText);
    } else if (lang === 'te') {
      adapted = adaptToTelugu(enText, hiText);
    } else if (lang === 'ta') {
      adapted = adaptToTamil(enText, hiText);
    }
    // Also apply any English clause replacements inside parenthetical segments
    for (const rule of CLAUSE_AND_WORD_REPLACEMENTS) {
      adapted = adapted.replace(rule.pattern, rule.replacements[lang]);
    }
    return adapted;
  }

  // Fallback when only English text is provided: apply comprehensive clause & vocabulary replacements
  let out = enText;
  for (const rule of CLAUSE_AND_WORD_REPLACEMENTS) {
    out = out.replace(rule.pattern, rule.replacements[lang]);
  }
  return out;
}
